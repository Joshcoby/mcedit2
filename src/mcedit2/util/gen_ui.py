"""
    gen_ui

    Compiles the Qt Designer .ui files in mcedit2/ui into Python modules using pyside6-uic.
"""
from __future__ import absolute_import, division, print_function
import logging
import os
import subprocess
import sys

log = logging.getLogger(__name__)


def _toolCommand(tool):
    scriptDir = os.path.dirname(sys.executable)
    for name in (tool, tool + ".exe"):
        path = os.path.join(scriptDir, name)
        if os.path.exists(path):
            return [path]
    return [tool]


def _uicCommand():
    # Prefer the pyside6-uic script that sits next to the running interpreter (virtualenv),
    # fall back to PySide6's bundled uic module.
    scriptDir = os.path.dirname(sys.executable)
    for name in ("pyside6-uic", "pyside6-uic.exe"):
        path = os.path.join(scriptDir, name)
        if os.path.exists(path):
            return [path]
    return [sys.executable, "-m", "PySide6.scripts.pyside_tool", "uic"]


def compile_ui(force=False):
    from mcedit2.util import resources
    if not resources.isSrcCheckout():
        return

    src = resources.getSrcFolder()
    uiDir = os.path.join(src, "mcedit2", "ui")

    log.info("Compiling .ui files...")
    uic = _uicCommand()
    for dirpath, dirnames, filenames in os.walk(uiDir):
        for filename in filenames:
            if not filename.endswith(".ui"):
                continue
            uiPath = os.path.join(dirpath, filename)
            pyPath = uiPath[:-3] + ".py"
            if (not force and os.path.exists(pyPath)
                    and os.path.getmtime(pyPath) >= os.path.getmtime(uiPath)):
                continue
            subprocess.check_call(uic + [uiPath, "-o", pyPath])

    # The generated UI modules do `import mcedit2_rc` for the compiled resources in mcedit2.qrc
    qrcPath = os.path.join(uiDir, "mcedit2.qrc")
    rcPath = os.path.join(src, "mcedit2_rc.py")
    if force or not os.path.exists(rcPath) or os.path.getmtime(rcPath) < os.path.getmtime(qrcPath):
        try:
            subprocess.check_call(_toolCommand("pyside6-rcc") + ["-o", rcPath, qrcPath], cwd=uiDir)
        except subprocess.CalledProcessError:
            # mcedit2.qrc lists files that are not in the repository (and nothing loads them), so rcc fails.
            # Write an empty resource module so the generated `import mcedit2_rc` lines still work.
            log.warning("Could not compile %s; writing an empty mcedit2_rc module.", qrcPath)
            with open(rcPath, "w") as f:
                f.write("# Generated by mcedit2.util.gen_ui: mcedit2.qrc could not be compiled (missing files).\n")
    log.info("Done.")

if __name__ == '__main__':
    compile_ui()
